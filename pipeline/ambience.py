"""Put a finished song in a place, so it sounds recorded there: python -m pipeline.ambience WEEK [--space NAME]

The week's audio.mp3 is split into vocals and instrumental (ElevenLabs stem separation, the same split
pipeline.revoice makes). The vocal gets the microphone roll-off and the room's reflections, a quiet
bed of room tone runs under the whole song and ducks a little whenever the voice sings, and the three are
mixed back to the same length. Word timings do not move, so the subtitles and timeline stay valid.
The guidelines this follows are in AMBIENCE.md. Working files are kept in output/WEEK/ambience/.

    --space NAME        studio (default), room, hall, carpark, outdoor, street, rain; --spaces lists them
    --bed synth|sfx     where the room tone comes from: built from noise in FFmpeg (default, free), or
                        generated by ElevenLabs sound effects from --prompt (spends credits)
    --prompt TEXT       what the generated bed should be, such as "light rain on a quiet street at night"
    --amount N          how much of the place is heard: 1 is the default, 0.5 half, 1.5 more (0 to 2)
    --out NAME          write output/WEEK/ambience/NAME.mp3 instead of replacing audio.mp3

The split spends ElevenLabs credits once per week and is reused. The original is kept as
output/WEEK/ambience/original.mp3; every run starts from it, so the step can be repeated.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import shutil
import subprocess
import sys
import urllib.error
import urllib.request
from pathlib import Path

from . import elevenlabs, listen, revoice
from .episode import Episode
from .settings import OUTPUT_DIR, RunError, log

SFX_URL = "https://api.elevenlabs.io/v1/sound-generation?output_format=mp3_44100_128"
SFX_MODEL = "eleven_text_to_sound_v2"
SFX_SECONDS = 30  # the longest one generation gives; it is made as a loop and repeated under the song
RATE = 44100

# One place each. hp/lp: the microphone roll-off on the voice (Hz). rt: how long the room rings (seconds).
# wet: the reflections against the voice (dB). pre: the gap before the first reflection (ms).
# slap: a single short echo off a far wall (ms, 0 for none) and its level (dB).
# bed: the synthesised room tone. bed_db: the bed against the whole song (dB). duck: how far the bed
# dips under the voice (dB).
SPACES = {
    "studio":  dict(hp=80, lp=11000, rt=0.30, wet=-24, pre=8, slap=0, slap_db=0, bed="room", bed_db=-40, duck=1.0,
                    note="a small treated room: the voice gets a little air and the silence gets a floor"),
    "room":    dict(hp=90, lp=10000, rt=0.50, wet=-20, pre=10, slap=0, slap_db=0, bed="room", bed_db=-36, duck=1.0,
                    note="a bedroom or a small shop: short, warm reflections"),
    "hall":    dict(hp=90, lp=9500, rt=1.30, wet=-19, pre=22, slap=0, slap_db=0, bed="room", bed_db=-36, duck=1.5,
                    note="a trading floor, a station hall, a lobby: a long soft tail"),
    "carpark": dict(hp=100, lp=9000, rt=1.90, wet=-17, pre=28, slap=0, slap_db=0, bed="rumble", bed_db=-33, duck=1.5,
                    note="concrete: hard, long reflections, traffic rumble and the hum of the lights"),
    "outdoor": dict(hp=100, lp=9500, rt=0.15, wet=-26, pre=0, slap=32, slap_db=-20, bed="wind", bed_db=-34, duck=1.5,
                    note="open air: almost no echo, one short slap, wind"),
    "street":  dict(hp=100, lp=9500, rt=0.25, wet=-24, pre=0, slap=36, slap_db=-19, bed="rumble", bed_db=-33, duck=1.5,
                    note="a street between buildings: a short slap off the walls over distant traffic"),
    "rain":    dict(hp=100, lp=9000, rt=0.25, wet=-24, pre=0, slap=36, slap_db=-20, bed="rain", bed_db=-32, duck=2.0,
                    note="a wet street: the street's slap under steady rain"),
}


def db(gain: float) -> float:
    return 10 ** (gain / 20)


def scale(space: dict, amount: float) -> dict:
    """The space with more or less of the place in it. Each halving of the amount takes 6 dB off the
    reflections, the slap and the bed; the microphone roll-off does not change."""
    if amount <= 0:
        return dict(space, wet=-120, slap_db=-120, bed_db=-120)
    shift = 20 * math.log10(amount)
    return dict(space, wet=space["wet"] + shift, slap_db=space["slap_db"] + shift, bed_db=space["bed_db"] + shift)


def impulse_graph(rt: float) -> str:
    """A room's ring as a filter graph: two channels of noise that die away by 60 dB in rt seconds."""
    def side(seed: int, name: str) -> str:
        return (f"anoisesrc=d={rt:.2f}:c=white:r={RATE}:seed={seed},volume='exp(-6.91*t/{rt:.2f})':eval=frame,"
                f"highpass=f=250,lowpass=f=7000[{name}]")
    return f"{side(11, 'l')};{side(29, 'r')};[l][r]join=inputs=2:channel_layout=stereo"


def bed_graph(kind: str, seconds: float) -> str:
    """Room tone built from noise: each layer on two channels, then mixed."""
    def noise(colour: str, seed: int, chain: str, name: str) -> str:
        sides = "".join(f"anoisesrc=d={seconds:.2f}:c={colour}:r={RATE}:seed={seed + n},{chain}[{name}{n}];" for n in (0, 1))
        return f"{sides}[{name}0][{name}1]join=inputs=2:channel_layout=stereo[{name}]"
    hum = f"sine=f=100:r={RATE}:d={seconds:.2f},volume=0.02,aformat=channel_layouts=stereo[hum]"
    layers = {
        # the floor of a quiet room: low rumble and a breath of air
        "room": [noise("brown", 3, "lowpass=f=300", "low"), noise("pink", 7, "highpass=f=2500,lowpass=f=7000,volume=0.25", "air")],
        # far traffic that swells and falls, and the lights
        "rumble": [noise("brown", 3, "lowpass=f=160,tremolo=f=0.11:d=0.5", "low"),
                   noise("pink", 7, "bandpass=f=700:w=600,tremolo=f=0.17:d=0.7,volume=0.2", "mid"), hum],
        # gusts
        "wind": [noise("pink", 3, "bandpass=f=450:w=500,tremolo=f=0.13:d=0.7", "gust"),
                 noise("brown", 7, "lowpass=f=200,volume=0.6", "low")],
        # rain on the ground, and the street under it
        "rain": [noise("white", 3, "highpass=f=1800,lowpass=f=8500,tremolo=f=0.19:d=0.25", "rain"),
                 noise("brown", 7, "lowpass=f=220,volume=0.7", "low")],
    }[kind]
    names = "".join(f"[{re.search(r'\[(\w+)\]$', layer).group(1)}]" for layer in layers)
    return ";".join(layers) + f";{names}amix=inputs={len(layers)}:normalize=0"


def mix_graph(space: dict, wet_gain: float, bed_gain: float) -> str:
    """The final mix. Inputs: 0 instrumental, 1 vocal, 2 the vocal's reflections, 3 the bed."""
    eq = f"highpass=f={space['hp']},lowpass=f={space['lp']}:p=1"
    voice = ["[1:a]aformat=channel_layouts=stereo," + eq + ",asplit=3[dry][key][tap]",
             f"[2:a]adelay={space['pre']}:all=1,volume={db(wet_gain):.5f}[wet]"]
    parts = "[0:a][dry][wet][bed]"
    if space["slap"]:
        # one echo, a few milliseconds apart on the two sides so it sits beside the voice, not on it
        voice.append(f"[tap]adelay={space['slap']}|{space['slap'] + 7},lowpass=f=5000,volume={db(space['slap_db']):.5f}[slap]")
        parts += "[slap]"
    else:
        voice.append("[tap]anullsink")
    # The bed dips by about `duck` dB while the voice sings and swells back in the gaps.
    ratio = 1 / (1 - space["duck"] / 18)  # the voice sits roughly 18 dB over the threshold when it sings
    bed = (f"[3:a]aformat=channel_layouts=stereo,volume={db(bed_gain):.5f}[b];"
           f"[b][key]sidechaincompress=threshold=0.02:ratio={ratio:.3f}:attack=25:release=450[bed]")
    return ";".join(voice) + ";" + bed + f";{parts}amix=inputs={parts.count('[')}:normalize=0,alimiter=limit=0.97[m]"


def mean_volume(path: Path) -> float:
    """The file's mean level in dB, as FFmpeg's volumedetect reports it."""
    done = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(path), "-af", "volumedetect", "-f", "null", "-"],
                          capture_output=True, text=True)
    found = re.search(r"mean_volume:\s*(-?[\d.]+) dB", done.stderr)
    if not found:
        raise RunError(f"The level of {path.name} could not be measured")
    return float(found.group(1))


def generate_bed(prompt: str, target: Path, api_key: str) -> None:
    """A looping bed from ElevenLabs sound effects (spends credits)."""
    body = json.dumps({"text": prompt, "duration_seconds": SFX_SECONDS, "prompt_influence": 0.5, "loop": True,
                       "model_id": SFX_MODEL}).encode("utf-8")
    request = urllib.request.Request(SFX_URL, data=body, method="POST",
                                     headers={"xi-api-key": api_key, "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(request, timeout=300) as response:
            target.write_bytes(response.read())
    except urllib.error.HTTPError as exc:
        raise RunError(f"ElevenLabs answered {exc.code}: {exc.read().decode('utf-8', 'replace')[:400]}") from exc
    except (OSError, TimeoutError) as exc:
        raise RunError(f"ElevenLabs could not be reached: {exc}") from exc


def heard(episode: Episode, audio: Path) -> float | None:
    """The share of the lyric words Whisper hears in this file, or None if the episode has no song.json."""
    if not episode.song_json.exists():
        return None
    from .stages.audio import assess
    return assess(episode.read_json(episode.song_json), listen.transcribe(audio))["coverage"]


def main() -> int:
    parser = argparse.ArgumentParser(prog="pipeline.ambience", description=__doc__.split("\n")[0])
    parser.add_argument("week", nargs="?")
    parser.add_argument("--space", default="studio", choices=sorted(SPACES))
    parser.add_argument("--spaces", action="store_true")
    parser.add_argument("--bed", default="synth", choices=["synth", "sfx"])
    parser.add_argument("--prompt")
    parser.add_argument("--amount", type=float, default=1.0)
    parser.add_argument("--out")
    args = parser.parse_args()
    if sys.stdout is not None and hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    try:
        if args.spaces:
            for name, space in SPACES.items():
                print(f"{name:8} {space['note']}")
            return 0
        if not args.week:
            raise RunError("Give a week such as 2026-W44. --spaces lists the places.")
        if not 0 <= args.amount <= 2:
            raise RunError("--amount must be between 0 and 2")
        if args.bed == "sfx" and not args.prompt:
            raise RunError("--bed sfx needs --prompt, the sound of the place in a few words")
        api_key = elevenlabs.load_api_key()
        if not api_key:
            raise RunError("No ElevenLabs API key found. Put ELEVENLABS_API_KEY=your-key in config\\.env")
        episode = Episode(OUTPUT_DIR, args.week)
        work = episode.dir / "ambience"
        work.mkdir(parents=True, exist_ok=True)
        original = work / "original.mp3"
        if not original.exists():
            shutil.copyfile(episode.audio_mp3, original)  # every run starts from the song as it was generated
        vocals, music = revoice.split(original, work, api_key)
        seconds = listen.duration(original)
        space = scale(SPACES[args.space], args.amount)

        # The room's reflections of the vocal alone, after the same roll-off the dry voice gets.
        impulse, wet = work / f"impulse_{args.space}.wav", work / f"wet_{args.space}.wav"
        revoice.ffmpeg("-f", "lavfi", "-i", impulse_graph(space["rt"]), "-c:a", "pcm_f32le", str(impulse))
        revoice.ffmpeg("-i", str(vocals), "-i", str(impulse), "-filter_complex",
                       f"[0:a]aformat=channel_layouts=stereo,highpass=f={space['hp']},lowpass=f={space['lp']}:p=1[v];"
                       "[v][1:a]afir=dry=0:wet=1:gtype=none:irnorm=-1[w]",
                       "-map", "[w]", "-t", f"{seconds:.3f}", "-c:a", "pcm_f32le", str(wet))

        if args.bed == "sfx":
            source = work / ("bed_" + re.sub(r"\W+", "-", args.prompt.lower()).strip("-")[:60] + ".mp3")
            if not source.exists():
                log("ambience: generating the bed with ElevenLabs sound effects (spends credits)")
                generate_bed(args.prompt, source, api_key)
            bed_input = ["-stream_loop", "-1", "-i", str(source)]
        else:
            source = work / f"bed_{space['bed']}.wav"
            revoice.ffmpeg("-f", "lavfi", "-i", bed_graph(space["bed"], seconds), "-c:a", "pcm_f32le", str(source))
            bed_input = ["-i", str(source)]

        # Levels are set against what is measured, not guessed: the reflections against the voice,
        # the bed against the whole song.
        wet_gain = (mean_volume(vocals) + space["wet"]) - mean_volume(wet)
        bed_gain = (mean_volume(original) + space["bed_db"]) - mean_volume(source)
        target = work / f"{args.out}.mp3" if args.out else episode.audio_mp3
        revoice.ffmpeg("-i", str(music), "-i", str(vocals), "-i", str(wet), *bed_input, "-filter_complex",
                       mix_graph(space, wet_gain, bed_gain), "-map", "[m]", "-t", f"{seconds:.3f}",
                       "-c:a", "libmp3lame", "-b:a", "192k", str(target))

        before, after = heard(episode, original), heard(episode, target)
        report = {"space": args.space, "amount": args.amount, "bed": args.prompt if args.bed == "sfx" else space["bed"],
                  "settings": {k: v for k, v in space.items() if k != "note"},
                  "wet_gain_db": round(wet_gain, 1), "bed_gain_db": round(bed_gain, 1),
                  "level_before_db": mean_volume(original), "level_after_db": mean_volume(target),
                  "words_heard_before": before, "words_heard_after": after, "file": target.name}
        episode.write_json(work / f"{args.out or 'ambience'}.json", report)
        log(f"ambience: wrote {target} ({args.space}, amount {args.amount:g})"
            + (f"; words heard {before:.0%} before, {after:.0%} after" if before is not None else ""))
        if before is not None and after < before - 0.1:
            log("ambience: the place is covering the words; run it again with a lower --amount")
            return 2
        return 0
    except RunError as exc:
        log(f"FAILED: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
